// 8125A-2 boards with swapped MDI pairs: each pair's
// calibration to its mirror pair.
fn mdiSwap() void {
    var adc: [4]u16 = undefined;
    ocpBits(0xD068, 0x07, 0x01);
    for (0..4) |p| {
        ocpBits(0xD068, 0x18, @intCast(p << 3));
        adc[p] = ocpRead(0xD06A) & 0x07FF;
    }
    for (0..4) |p| {
        ocpBits(0xD068, 0x18, @intCast(p << 3));
        ocpBits(0xD06A, 0x07FF, adc[3 - p]);
    }
    // Pairs 0 and 1 at lo, 2 and 3 at lo + 2:
    for ([_]u16{ 0xBD5A, 0xBC18 }) |lo| {
        const a = ocpRead(lo);
        const b = ocpRead(lo + 2);
        ocpBits(lo, 0x001F, (b & 0x1F00) >> 8);
        ocpBits(lo, 0x1F00, (b & 0x001F) << 8);
        ocpBits(lo + 2, 0x001F, (a & 0x1F00) >> 8);
        ocpBits(lo + 2, 0x1F00, (a & 0x001F) << 8);
    }
}

