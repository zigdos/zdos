// By MAC version (if_re.c's MACFG numbers).
pub fn config(mac: u8) void {
    switch (mac) {
        56 => g1(),
        58 => gu1(),
        59 => gu2(),
        60 => r8411b(),
        61 => ep1(),
        62, 67 => ep2(),
        68 => h1(),
        69, 76 => h2(),
        70...73 => fp1(),
        74 => h3(),
        75 => h4(),
        80 => a8125_1(),
        81 => a8125_2(),
        82 => b8125_1(),
        83 => b8125_2(),
        else => {},
    }
}

